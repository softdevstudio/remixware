func TestCargoLock(t *testing.T) {
	lock := `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "local-helper",
 "serde",
 "Fancy_Name",
 "forked 0.3.0 (git+https://github.com/example/forked?branch=main#abc)",
]

[[package]]
name = "local-helper"
version = "0.1.0"
dependencies = [
 "memchr",
]

[[package]]
name = "serde"
version = "1.0.210"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aa"
dependencies = [
 "serde_derive",
]

[[package]]
name = "serde_derive"
version = "1.0.210"
source = "sparse+https://index.crates.io/"
checksum = "bb"

[[package]]
name = "memchr"
version = "2.7.4"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "cc"

[[package]]
name = "Fancy_Name"
version = "0.2.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "dd"

[[package]]
name = "forked"
version = "0.3.0"
source = "git+https://github.com/example/forked?branch=main#abc"

[[package]]
name = "inhouse"
version = "1.0.0"
source = "registry+https://crates.example.net/index"
checksum = "ee"
`
	m := pkgMap(t)(parseCargoLock([]byte(lock)))
	if len(m) != 6 {
		t.Errorf("%d packages, want 6 (the two path crates left out): %v", len(m), m)
	}
	if p := m["serde@1.0.210"]; !p.direct || !p.registry || p.eco != EcoCargo || p.scripts != scriptsUnknown {
		t.Errorf("serde: %+v", p)
	}
	if p := m["serde_derive@1.0.210"]; p.direct || !p.registry {
		t.Errorf("serde_derive (transitive, sparse index): %+v", p)
	}
	if p := m["memchr@2.7.4"]; !p.direct {
		t.Errorf("memchr, a dependency of a path crate, is direct: %+v", p)
	}
	if p := m["forked@0.3.0"]; !p.direct || p.registry {
		t.Errorf("git crate: %+v", p)
	}
	if p := m["inhouse@1.0.0"]; p.registry {
		t.Errorf("another registry counted as crates.io: %+v", p)
	}
	for name, bad := range map[string]string{
		"version 2":       "version = 2\n",
		"a bad version":   "version = 4\n[[package]]\nname = \"a\"\nversion = \"latest\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n",
		"a bad name":      "version = 4\n[[package]]\nname = \"a b\"\nversion = \"1.0.0\"\n",
		"an unknown key":  "version = 4\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nfeatures = []\n",
		"replace":         "version = 4\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nreplace = \"b 1.0.0\"\n",
		"a source scheme": "version = 4\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nsource = \"path+file:///x\"\n",
		"a stray line":    "version = 4\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\ndependencies = [\n \"b\",\n junk\n]\n",
		"a top-level key": "version = 4\nwhatever = 1\n",
	} {
		if _, err := parseCargoLock([]byte(bad)); err == nil {
			t.Errorf("%s: read without an error", name)
		}
	}
	// Older files without a version line read too.
	if _, err := parseCargoLock([]byte("[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n\n[metadata]\n\"checksum a 1.0.0 (registry+https://github.com/rust-lang/crates.io-index)\" = \"aa\"\n")); err != nil {
		t.Errorf("a version 1 file: %v", err)
	}
}

func TestCargoAllowRuleNames(t *testing.T) {
	r := DepAllowRule{Package: "cargo/fancy-name", Reason: "x"}
	if !r.match(EcoCargo, "Fancy_Name") {
		t.Error("crates.io treats Fancy_Name and fancy-name as one crate")
	}
}

func crateFile(t *testing.T, name, version string, files map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for n, body := range files {
		tw.WriteHeader(&tar.Header{Name: name + "-" + version + "/" + n, Mode: 0o644, Size: int64(len(body))})
		tw.Write([]byte(body))
	}
	tw.Close()
	gz.Close()
	return buf.Bytes()
}

func moduleZip(t *testing.T, mod, version string, files map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for n, body := range files {
		w, _ := zw.Create(mod + "@" + version + "/" + n)
		w.Write([]byte(body))
	}
	zw.Close()
	return buf.Bytes()
}

func TestCrateBuildSurfaceOnline(t *testing.T) {
	f := newFakeRegistry(t)
	plain := "[package]\nname = \"x\"\nversion = \"1.0.0\"\n"
	cases := map[string]struct {
		files map[string]string
		runs  bool
	}{
		"plain":             {map[string]string{"Cargo.toml": plain, "src/lib.rs": ""}, false},
		"build.rs":          {map[string]string{"Cargo.toml": plain, "build.rs": "fn main(){}"}, true},
		"build = false":     {map[string]string{"Cargo.toml": "[package]\nname = \"x\"\nbuild = false\n", "build.rs": ""}, false},
		"build elsewhere":   {map[string]string{"Cargo.toml": "[package]\nname = \"x\"\nbuild = \"tools/gen.rs\"\n"}, true},
		"proc-macro":        {map[string]string{"Cargo.toml": plain + "\n[lib]\nproc-macro = true\n"}, true},
		"a nested build.rs": {map[string]string{"Cargo.toml": plain, "examples/build.rs": ""}, false},
	}
	i := 0
	for name, c := range cases {
		i++
		crate := "c" + strings.Repeat("x", i)
		f.raw["/crates/"+crate+"/"+crate+"-1.0.0.crate"] = crateFile(t, crate, "1.0.0", c.files)
		facts, _, err := f.registry("").Facts(EcoCargo, crate, "1.0.0")
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if facts.InstallScripts != c.runs {
			t.Errorf("%s: install scripts %v, want %v", name, facts.InstallScripts, c.runs)
		}
	}
	// Through the gate: a new crate with a build script fails as an install
	// script even when it's allowed; with install_scripts it passes.
	f.raw["/crates/cc/cc-1.1.0.crate"] = crateFile(t, "cc", "1.1.0", map[string]string{"Cargo.toml": plain, "build.rs": ""})
	base := genLock("cargo", []string{"a@1.0.0"})
	head := genLock("cargo", []string{"a@1.0.0", "cc@1.1.0"})
	res := compare(t, head, base, allowPolicy(DepAllowRule{Package: "cargo/cc", Reason: "C compiler driver"}), f.registry(""))
	if fs := DepFailures(res, DefaultDepFailOn); len(fs) != 1 || fs[0].Status != DepInstallScript {
		t.Errorf("cc with build.rs: %+v", res.Changes)
	}
	res = compare(t, head, base, allowPolicy(DepAllowRule{Package: "cargo/cc", Reason: "x", InstallScripts: true}), f.registry(""))
	if fs := DepFailures(res, DefaultDepFailOn); len(fs) != 0 {
		t.Errorf("allowed with install_scripts: %+v", fs)
	}
	for _, c := range res.Checks {
		if c.Name == "publisher" && c.NotRun[whyNoCrateData] != 1 {
			t.Errorf("the publisher check should say crates.io isn't checked: %+v", c)
		}
	}
}

func TestGoNativeCodeOnline(t *testing.T) {
	f := newFakeRegistry(t)
	cgo := "package x\n\n// #include <stdio.h>\nimport \"C\"\n"
	cases := map[string]struct {
		files  map[string]string
		native bool
	}{
		"plain":                  {map[string]string{"go.mod": "module m\n", "x.go": "package x\n"}, false},
		"cgo":                    {map[string]string{"go.mod": "module m\n", "x.go": cgo}, true},
		"cgo in an import block": {map[string]string{"x.go": "package x\n\nimport (\n\t\"C\"\n\t\"fmt\"\n)\n"}, true},
		"syso":                   {map[string]string{"x.go": "package x\n", "rsrc_windows_amd64.syso": "\x00"}, true},
		"cgo only in a test":     {map[string]string{"x.go": "package x\n", "x_test.go": cgo}, false},
		"cgo in testdata":        {map[string]string{"x.go": "package x\n", "testdata/c.go": cgo}, false},
		"cgo in a nested module": {map[string]string{"x.go": "package x\n", "sub/go.mod": "module m/sub\n", "sub/c.go": cgo}, false},
	}
	i := 0
	for name, c := range cases {
		i++
		mod := "example.com/M" + strings.Repeat("q", i)
		esc, _ := escapeModulePath(mod)
		f.raw["/goproxy/"+esc+"/@v/v1.0.0.zip"] = moduleZip(t, mod, "v1.0.0", c.files)
		facts, _, err := f.registry("").Facts(EcoGo, mod, "v1.0.0")
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if facts.NativeCode != c.native {
			t.Errorf("%s: native code %v, want %v", name, facts.NativeCode, c.native)
		}
	}
	// Through the gate: native-code reports without failing by default;
	// it fails when fail_on names it, and native_code allows it.
	mod := "example.com/sqlite"
	f.raw["/goproxy/"+mod+"/@v/v1.2.0.zip"] = moduleZip(t, mod, "v1.2.0", map[string]string{"go.mod": "module " + mod + "\n", "c.go": cgo})
	base := genLock("go", []string{"example.com/a@1.0.0"})
	head := genLock("go", []string{"example.com/a@1.0.0", mod + "@1.2.0"})
	pol := allowPolicy(DepAllowRule{Package: "golang/" + mod, Reason: "database driver"})
	res := compare(t, head, base, pol, f.registry(""))
	c := change(res, "golang/"+mod)
	if c == nil || c.Status != DepNativeCode || len(DepFailures(res, DefaultDepFailOn)) != 0 {
		t.Errorf("native code should report, not fail: %+v", res.Changes)
	}
	if len(DepFailures(res, append(DefaultDepFailOn, DepNativeCode))) != 1 {
		t.Error("fail_on native-code should fail it")
	}
	pol = allowPolicy(DepAllowRule{Package: "golang/" + mod, Reason: "database driver", NativeCode: true})
	if c := change(compare(t, head, base, pol, f.registry("")), "golang/"+mod); c == nil || c.Status != DepAllowed {
		t.Errorf("native_code allows it: %+v", c)
	}
	// Offline the check says it needs --online.
	res = compare(t, head, base, pol, nil)
	for _, ch := range res.Checks {
		if ch.Name == "native-code" && ch.NotRun[whyNeedsOnline] != 1 {
			t.Errorf("offline native-code check: %+v", ch)
		}
	}
}
